package it.ddot.core.conformance;

import it.ddot.core.io.DdotEventExporter;
import it.ddot.core.io.DdotParser;
import it.ddot.core.html.DdotHtmlRenderer;
import it.ddot.core.token.DdotTokenizer;
import it.ddot.core.token.Tokens;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.fail;

/**
 * Byte-exact conformance of {@link DdotTokenizer}, {@link DdotEventExporter} and
 * {@link DdotHtmlRenderer} against the
 * cross-implementation golden corpus in the {@code ddot.it} repo ({@code test-data/cases/}, 35 cases).
 *
 * <p>Each case directory holds {@code input.ddot} plus the goldens this test asserts:
 * <ul>
 *   <li>{@code expected.tokens.json} — the canonical highlighter token stream (see {@code test-data/tokens.md}),
 *       generated canonically by the TextMate grammar in {@code ddot.it-syntax-tools}. This side is
 *       <strong>read-only</strong> here: if it diverges, fix {@link DdotTokenizer}, never the corpus file.</li>
 *   <li>{@code expected.events.jsonl} — the triple-event stream (https://ddot.it/developer-guide.html#events),
 *       for which {@link DdotEventExporter} is the canonical Java generator.</li>
 *   <li>{@code expected.body.html} — role-classed preview markup, generated canonically by the Ruby renderer
 *       {@code ddot-render.rb} in the IntelliJ plugin. {@link DdotHtmlRenderer} is a mirror of it (and, in
 *       Java, a plain fold over the token stream above), so a divergence is a renderer bug.</li>
 * </ul>
 *
 * <p><strong>This test refuses to pass vacuously.</strong> The corpus lives in a sibling repository, so it can
 * legitimately be absent — in that case the test SKIPS and prints a loud stderr banner naming the path it looked
 * at and the {@code -D} override. But a corpus that is present and merely <em>truncated</em> is a bug, not a
 * configuration: fewer than {@value #MIN_CASES} case directories, or a case missing a golden file, is a
 * FAILURE. Silent green on an empty corpus has bitten this ecosystem twice.
 */
final class CorpusConformanceTest {

    /** Override for a corpus checked out somewhere other than as a sibling of this repo. */
    private static final String DIR_PROP = "ddot.corpus.dir";

    /** Sibling checkout of <a href="https://github.com/calpano/ddot.it">...</a>, resolved from this repo's root. */
    private static final Path DEFAULT_CASES = Path.of("..", "ddot.it", "test-data", "cases");

    /** The corpus has 35 cases; anything materially smaller means we are asserting against a stub. */
    static final int MIN_CASES = 30;

    private static final String EVENT_KIND = "ddot";
    private static final String EVENT_SOURCE = "input.ddot";

    @Test
    void tokenStreamMatchesCorpus() throws IOException {
        List<String> failures = new ArrayList<>();
        for (Path caseDir : cases()) {
            String input = Files.readString(requireFile(caseDir, "input.ddot"));
            check(requireFile(caseDir, "expected.tokens.json"),
                    Tokens.toJson(DdotTokenizer.tokenize(input)),
                    caseDir.getFileName().toString(), failures);
        }
        if (!failures.isEmpty()) {
            fail(failures.size() + " case(s) diverged from the canonical token corpus: "
                    + String.join(", ", failures)
                    + ". DdotTokenizer must match expected.tokens.json — that file is generated by the"
                    + " TextMate grammar in ddot.it-syntax-tools (`npm run regenerate:tokens`) and is"
                    + " canonical; fix the tokenizer, not the corpus.");
        }
    }

    @Test
    void eventStreamMatchesCorpus() throws IOException {
        List<String> failures = new ArrayList<>();
        for (Path caseDir : cases()) {
            String input = Files.readString(requireFile(caseDir, "input.ddot"));
            check(requireFile(caseDir, "expected.events.jsonl"),
                    DdotEventExporter.toJsonl(DdotParser.parse(input, EVENT_KIND, EVENT_SOURCE)),
                    caseDir.getFileName().toString(), failures);
        }
        if (!failures.isEmpty()) {
            fail(failures.size() + " case(s) diverged from the event corpus: "
                    + String.join(", ", failures)
                    + ". Either fix DdotEventExporter to match, or — if the exporter is right and the"
                    + " corpus is stale — regenerate expected.events.jsonl in the ddot.it repo.");
        }
    }

    @Test
    void bodyHtmlMatchesCorpus() throws IOException {
        List<String> failures = new ArrayList<>();
        for (Path caseDir : cases()) {
            String input = Files.readString(requireFile(caseDir, "input.ddot"));
            check(requireFile(caseDir, "expected.body.html"),
                    DdotHtmlRenderer.body(input),
                    caseDir.getFileName().toString(), failures);
        }
        if (!failures.isEmpty()) {
            fail(failures.size() + " case(s) diverged from the HTML corpus: "
                    + String.join(", ", failures)
                    + ". expected.body.html is generated by the canonical Ruby renderer (ddot-render.rb in"
                    + " the IntelliJ plugin); DdotHtmlRenderer is a mirror, so fix the renderer here.");
        }
    }

    // --- corpus resolution ---------------------------------------------------

    /**
     * The case directories, or a loud skip when the corpus is not checked out. Never returns an empty or
     * suspiciously short list: that fails instead, so a missing corpus can never masquerade as a pass.
     */
    private static List<Path> cases() throws IOException {
        Path dir = resolveCasesDir();
        if (!Files.isDirectory(dir)) {
            String msg = "ddot.it golden corpus not found at " + dir.toAbsolutePath().normalize();
            System.err.println();
            System.err.println("==================================================================");
            System.err.println("  SKIPPING ddot.it CORPUS CONFORMANCE TESTS");
            System.err.println("  looked for : " + dir.toAbsolutePath().normalize());
            System.err.println("  fix        : clone https://github.com/calpano/ddot.it as a sibling");
            System.err.println("               of this repo, or run with");
            System.err.println("               -D" + DIR_PROP + "=/abs/path/to/ddot.it/test-data/cases");
            System.err.println("  NOTE       : the tokenizer and event exporter are NOT being");
            System.err.println("               checked against the 35-case corpus in this run.");
            System.err.println("==================================================================");
            System.err.println();
            Assumptions.abort(msg + " — see the banner above. Override with -D" + DIR_PROP + "=<abs path>.");
        }
        List<Path> caseDirs;
        try (Stream<Path> s = Files.list(dir)) {
            caseDirs = s.filter(Files::isDirectory).sorted(Comparator.naturalOrder()).toList();
        }
        if (caseDirs.size() < MIN_CASES) {
            fail("The ddot.it corpus at " + dir.toAbsolutePath().normalize() + " has only "
                    + caseDirs.size() + " case(s); at least " + MIN_CASES + " are expected (the corpus has 35)."
                    + " A truncated corpus would make these conformance tests pass vacuously, so this is a"
                    + " failure, not a skip.");
        }
        return caseDirs;
    }

    /**
     * {@code -Dddot.corpus.dir} if set (pointing either at {@code cases/} itself or at the {@code test-data/}
     * directory containing it), else the sibling checkout. Relative paths resolve against the working
     * directory, which surefire sets to this repo's root.
     */
    private static Path resolveCasesDir() {
        String configured = System.getProperty(DIR_PROP);
        if (configured == null || configured.isBlank()) return DEFAULT_CASES;
        Path p = Path.of(configured.trim());
        Path nested = p.resolve("cases");
        return Files.isDirectory(nested) ? nested : p;
    }

    private static Path requireFile(Path caseDir, String name) {
        Path p = caseDir.resolve(name);
        if (!Files.isRegularFile(p)) {
            fail("Corpus case " + caseDir.getFileName() + " is missing " + name + " (" + p + ")."
                    + " An incomplete case would be silently skipped, so this is a failure.");
        }
        return p;
    }

    private static void check(Path expected, String actual, String label, List<String> failures) {
        String want;
        try {
            want = Files.readString(expected);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        if (!want.equals(actual)) {
            failures.add(label);
            System.err.println("[corpus] MISMATCH " + label + " (" + expected.getFileName() + ")");
            System.err.println("---- expected ----\n" + want);
            System.err.println("---- actual   ----\n" + actual);
        }
    }
}
